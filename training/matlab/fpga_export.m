function fpga_export(best, cfg)
%FPGA_EXPORT 把训练好的「3 子带 FBCSP + 欧氏对齐 + 线性 SVM」参数量化并导出
%
%   fpga_export(best, cfg)
%
%   best 字段：
%     .meta       含 subject / fs / G / win_export
%     .sos        1×B cell，每带 (n_sec × 6) 的 SOS（scipy 行格式）
%     .W          1×B cell，每带 (n_ch × n_comp)，**已含 EA 折叠**
%     .m          CSP 每侧对数
%     .selIdx     MIBIF 选中的特征索引（0 基，从 n_band×n_comp 维中选）
%     .mu, .sd    特征标准化参数（长度 = numel(selIdx)）
%     .w, .b      SVM 权重与偏置（**未标准化域**，已折算）
%     .bands      n_band × 2 的频带表
%     .nCal       校准试次数
%     .accCross   交叉验证准确率（仅记录）
%
%   产出（写到 ../params/）：
%     csp_svm_params.h    PL 测试平台与 PS 端共用
%     csp_svm_params.json 机器可读的唯一真实来源
%
%   定点格式严格遵循 规划/01_定点格式与接口约定.md §2 的位宽表。
%   ★ 归一化特征对全局缩放免疫，所以存的是整数域参数，不需要 µV 换算。

outDir = fullfile(fileparts(mfilename('fullpath')), '..', 'params');
if ~exist(outDir, 'dir'), mkdir(outDir); end

% ── 各节点的 Q 格式（小数位）────────────────────────────────
q = struct();
q.sos = 14;   % 带通 IIR 系数   Q3.14 (18 bit)
q.W   = 14;   % CSP 权重        Q3.14 (18 bit) ★ EA 折叠后动态范围变大，Q2.14/16bit 会溢出
q.w   = 11;   % SVM 权重        Q4.11 (16 bit)，与特征同域
q.b   = 23;   % SVM 偏置        Q8.23 (32 bit)
q.dc  = 15;   % 去DC 高通系数    Q1.15 (16 bit)
q.feat= 11;   % 特征            Q4.11
q.z   = 13;   % CSP 投影 z      Q10.13

nBand = numel(best.W);
nCh   = size(best.W{1}, 1);
nComp = size(best.W{1}, 2);
nFeatAll = nBand * nComp;
kSel  = numel(best.selIdx);
fs    = best.meta.fs;

% ── 量化 ────────────────────────────────────────────────────
sosQ = cell(1, nBand);
for b = 1:nBand
    sosQ{b} = round(best.sos{b}(:, [1 2 3 5 6]) * 2^q.sos);   % {b0,b1,b2,a1,a2}
end
Wq   = cellfun(@(W) round(W * 2^q.W), best.W, 'uni', 0);
wq   = round(best.w(:) * 2^q.w);
bq   = round(best.b * 2^q.b);
dcA  = round(1/(1 + 2*pi*0.5/fs) * 2^q.dc);
winN = round(diff(cfg.tUse) * fs) + 1;

% ── 溢出检查（定点化最常翻车的地方）────────────────────────
fprintf('  定点溢出检查：\n');
for b = 1:nBand
    check_range(sosQ{b}, 18, sprintf('IIR 系数 带%d Q3.14', b));
end
for b = 1:nBand
    check_range(Wq{b}, 18, sprintf('CSP 权重 带%d Q3.14', b));
end
check_range(wq, 16, 'SVM 权重 Q4.11');
check_range(bq, 32, 'SVM 偏置 Q8.23');
check_range(dcA, 16, '去DC 系数 Q1.15');

% ── 写 C 头文件 ─────────────────────────────────────────────
hPath = fullfile(outDir, 'csp_svm_params.h');
fid = fopen(hPath, 'w');
if fid < 0, error('无法写入 %s', hPath); end
stamp = datestr(now, 'yyyy-mm-ddTHH:MM:SS'); %#ok<DATST,TNOW1>

fprintf(fid, '/* AUTO-GENERATED by matlab/fpga_export.m — DO NOT EDIT\n');
fprintf(fid, ' * 算法: 3 子带 FBCSP + 欧氏对齐 + 归一化对数方差 + 线性 SVM\n');
fprintf(fid, ' * 数据: BCI Competition IV 2b, subject %02d\n', best.meta.subject);
fprintf(fid, ' * 生成: %s\n', stamp);
fprintf(fid, ' * cross 协议准确率 %.2f%% (kappa %+.3f)\n */\n', ...
        best.accCross*100, 2*best.accCross-1);
fprintf(fid, '#ifndef CSP_SVM_PARAMS_H\n#define CSP_SVM_PARAMS_H\n\n');
fprintf(fid, '#include <stdint.h>\n\n');
fprintf(fid, '#define PARAM_VERSION   "%s"\n', stamp);
fprintf(fid, '#define N_CH            %d\n', nCh);
fprintf(fid, '#define WIN_LEN         %d\n', winN);
fprintf(fid, '#define N_BAND          %d   /* 子带数 */\n', nBand);
fprintf(fid, '#define N_COMP          %d   /* 每带 = min(2m, N) */\n', nComp);
fprintf(fid, '#define N_FEAT_ALL      %d   /* = N_BAND * N_COMP */\n', nFeatAll);
fprintf(fid, '#define FEAT_DIM        %d   /* MIBIF 选中数 */\n', kSel);
fprintf(fid, '#define IIR_SEC_PER_BAND %d\n', size(sosQ{1},1));
fprintf(fid, '#define SVM_KERNEL_LINEAR 1\n');
fprintf(fid, '#define Q_IIR           %d\n#define Q_CSP_W         %d\n', q.sos, q.W);
fprintf(fid, '#define Q_SVM_W         %d\n#define Q_SVM_B         %d\n', q.w, q.b);
fprintf(fid, '#define Q_FEAT          %d\n#define Q_Z             %d\n', q.feat, q.z);
fprintf(fid, '#define Q_DC            %d\n\n', q.dc);

fprintf(fid, '/* 去直流一阶高通 0.5 Hz:  y[n] = a*(y[n-1] + x[n] - x[n-1]) */\n');
fprintf(fid, 'static const int16_t DC_A_Q1_15 = %d;\n\n', dcA);

fprintf(fid, '/* 3 子带带通，每带 4 阶巴特沃斯 = 2 个二阶段 {b0,b1,b2,a1,a2} @ Q%d */\n', q.sos);
for b = 1:nBand
    fprintf(fid, '/* band %d: %.0f-%.0f Hz */\n', b, best.bands(b,1), best.bands(b,2));
    fprintf(fid, 'static const int32_t IIR_SOS_B%d[IIR_SEC_PER_BAND][5] = {\n', b);
    for k = 1:size(sosQ{b},1)
        fprintf(fid, '    { %6d, %6d, %6d, %6d, %6d },\n', sosQ{b}(k,:));
    end
    fprintf(fid, '};\n');
end
fprintf(fid, 'static const int32_t * const IIR_SOS[N_BAND] = { IIR_SOS_B1');
for b = 2:nBand, fprintf(fid, ', IIR_SOS_B%d', b); end
fprintf(fid, ' };\n\n');

fprintf(fid, '/* CSP 空间滤波器 @ Q%d / 18bit，每带 (%d 通道 x %d 分量)，行优先\n', q.W, nCh, nComp);
fprintf(fid, ' * ★ 已含欧氏对齐折叠：W_eff = M_b^T * W~_b ，PL 侧不感知 EA */\n');
for b = 1:nBand
    fprintf(fid, 'static const int32_t CSP_W_B%d[N_CH * N_COMP] = {\n    ', b);
    for c = 1:nCh
        for j = 1:nComp
            fprintf(fid, '%6d, ', Wq{b}(c,j));
        end
        if c < nCh, fprintf(fid, '\n    '); end
    end
    fprintf(fid, '\n};\n');
end
fprintf(fid, 'static const int32_t * const CSP_W[N_BAND] = { CSP_W_B1');
for b = 2:nBand, fprintf(fid, ', CSP_W_B%d', b); end
fprintf(fid, ' };\n\n');

fprintf(fid, '/* MIBIF 特征索引（从 %d 维中选 %d 维，0 基）*/\n', nFeatAll, kSel);
fprintf(fid, 'static const uint8_t MIBIF_SEL_IDX[FEAT_DIM] = { ');
fprintf(fid, '%d, ', best.selIdx(:));
fprintf(fid, '};\n\n');

fprintf(fid, '/* 特征标准化参数（PL 端 f_norm = (f - mu) / sd）*/\n');
fprintf(fid, 'static const int16_t FEAT_MU_Q11[FEAT_DIM] = { ');
fprintf(fid, '%6d, ', round(best.mu(:)*2^q.feat));  fprintf(fid, '};\n');
fprintf(fid, 'static const int16_t FEAT_SD_Q11[FEAT_DIM] = { ');
fprintf(fid, '%6d, ', round(best.sd(:)*2^q.feat));  fprintf(fid, '};\n\n');

fprintf(fid, '/* SVM 线性核已折叠: d(f) = w.f + b */\n');
fprintf(fid, 'static const int16_t SVM_W[FEAT_DIM] = { ');
fprintf(fid, '%6d, ', wq);  fprintf(fid, '};\n');
fprintf(fid, 'static const int32_t SVM_B_Q8_23 = %d;\n\n', bq);
fprintf(fid, '#endif /* CSP_SVM_PARAMS_H */\n');
fclose(fid);
fprintf('  -> %s\n', hPath);

% ── 写 JSON ────────────────────────────────────────────────
jPath = fullfile(outDir, 'csp_svm_params.json');
J = struct();
J.version = stamp;
J.dataset = 'BCI_IV_2b';
J.subject = sprintf('B%02d', best.meta.subject);
J.fs = fs;  J.n_ch = nCh;  J.win_len = winN;
J.n_band = nBand;  J.bands = best.bands;
J.m = best.m;  J.n_comp = nComp;  J.n_feat_all = nFeatAll;  J.feat_dim = kSel;
J.feature = 'logvar_norm';
J.ea = struct('n_cal', best.nCal, 'folded', true, 'mean_type', 'arithmetic');
J.q_formats = struct('sos',q.sos,'csp_W',q.W,'csp_W_bits',18,'svm_w',q.w,'svm_b',q.b,'feat',q.feat,'z',q.z);
J.dc_a_q1_15 = dcA;
J.iir = struct('type','butter','order',4,'sections_per_band',size(sosQ{1},1), ...
               'bands', best.bands, 'sos_q', {sosQ});
J.csp_W = Wq;                      % cell，每带
J.mibif_sel_idx = best.selIdx(:).';
J.feat_norm = struct('mu_q11', round(best.mu(:)*2^q.feat).', ...
                     'sd_q11', round(best.sd(:)*2^q.feat).');
J.svm = struct('kernel','linear','w',wq.','b',bq);
J.accuracy = struct('cross', best.accCross, 'kappa_cross', 2*best.accCross-1);
txt = jsonencode(J, 'PrettyPrint', true);
fid2 = fopen(jPath, 'w'); fprintf(fid2, '%s', txt); fclose(fid2);
fprintf('  -> %s\n', jPath);

fprintf('\n  参数摘要: N_CH=%d  N_BAND=%d  N_COMP=%d  N_FEAT_ALL=%d  FEAT_DIM=%d  WIN_LEN=%d\n', ...
        nCh, nBand, nComp, nFeatAll, kSel, winN);
fprintf('            MIBIF 选中 %s（0 基）\n', mat2str(best.selIdx(:).'));
fprintf('            SVM 权重 %s @ Q%d, 偏置 %d @ Q%d\n', mat2str(wq.'), q.w, bq, q.b);
end


function check_range(v, bits, name)
    lo = -2^(bits-1);  hi = 2^(bits-1) - 1;
    mx = max(abs(v(:)));
    if mx > hi
        fprintf('    [溢出] %-22s 最大 %d > %d\n', name, mx, hi);
    else
        fprintf('    [ OK ] %-22s 最大 %6d / 上限 %6d  (余量 %.0f%%)\n', ...
                name, mx, hi, (1 - mx/hi)*100);
    end
    if lo > min(v(:))
        fprintf('    [下溢] %-22s 最小 %d < %d\n', name, min(v(:)), lo);
    end
end
